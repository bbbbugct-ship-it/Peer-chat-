/**
 * Onboarding screen for new accounts or editing profile:
 * Users pick their Display Name, @username handle, and in-app password/PIN.
 */
@Composable
fun ProfileSetupScreen(
    initialProfile: UserProfile?,
    onSaveProfile: (displayName: String, username: String, bio: String, avatarColor: String, appPassword: String) -> Unit,
    onSignOut: () -> Unit
