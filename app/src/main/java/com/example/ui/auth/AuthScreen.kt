    var username by remember { mutableStateOf(initialProfile?.username ?: "") }
    var bio by remember { mutableStateOf(initialProfile?.bio ?: "Available") }
    var appPassword by remember { mutableStateOf(initialProfile?.appPassword ?: "") }
    var selectedColor by remember { mutableStateOf(initialProfile?.avatarColor ?: "#0084FF") }
    var isPasswordVisible by remember { mutableStateOf(false) }
    var errorText by remember { mutableStateOf<String?>(null) }

    val avatarColors = listOf(
        "#0084FF", // Messenger Blue
        "#00C6FF", // Cyan
        "#9333EA", // Purple
        "#10B981", // Emerald
        "#EF4444", // Coral
        "#F59E0B"  // Amber
    )

    Box(
        modifier = Modifier
            .fillMaxSize()
            .background(MaterialTheme.colorScheme.background)
            .padding(24.dp),
        contentAlignment = Alignment.Center
    ) {
        Card(
            shape = RoundedCornerShape(24.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
            elevation = CardDefaults.cardElevation(defaultElevation = 3.dp),
            modifier = Modifier
                .fillMaxWidth()
                .verticalScroll(rememberScrollState())
        ) {
            Column(
                modifier = Modifier.padding(24.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                // Avatar preview
                Box(
                    modifier = Modifier
                        .size(80.dp)
                        .clip(CircleShape)
                        .background(
                            try {
                                Color(android.graphics.Color.parseColor(selectedColor))
                            } catch (e: Exception) {
                                MessengerBlue
                            }
                        ),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = (displayName.ifBlank { "U" }).take(1).uppercase(),
                        color = Color.White,
                        fontSize = 32.sp,
                        fontWeight = FontWeight.Bold
                    )
                }

                Spacer(modifier = Modifier.height(16.dp))

                Text(
                    text = if (initialProfile?.displayName.isNullOrBlank()) "Set up Messenger Profile" else "Edit Profile",
                    style = MaterialTheme.typography.titleLarge,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )

                Text(
                    text = "Pick your public chat name and in-app password",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )

                Spacer(modifier = Modifier.height(20.dp))

